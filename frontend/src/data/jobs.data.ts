function buildFullJob(item: JobListItem): Job {
  return {
    id: item.id,
    jobNumber: item.jobNumber,
    title: item.title,
    description: `Service request: ${item.title}. Customer has reported the issue and requires on-site inspection and resolution.`,
    customerId: `cust-${item.id}`,
    customerName: item.customerName,
    customerPhone: item.customerPhone,
    customerEmail: `${item.customerName.toLowerCase().replace(/\s+/g, '.')}@email.com`,
    contactPerson: item.customerName,
    serviceType: item.serviceType,
    priority: item.priority,
    status: item.status,
    serviceAddress: item.serviceAddress,
    scheduledDate: item.scheduledDate,
    scheduledTime: item.scheduledTime,
    estimatedDuration: item.estimatedDuration,
    actualStartTime:
      item.status === 'in_progress' || item.status === 'completed' || item.status === 'invoiced'
        ? `${item.scheduledDate}T${item.scheduledTime}:00Z`
        : undefined,
    actualEndTime:
      item.status === 'completed' || item.status === 'invoiced'
        ? `${item.scheduledDate}T${String(Number(item.scheduledTime.split(':')[0]) + Math.floor(item.estimatedDuration / 60)).padStart(2, '0')}:${item.scheduledTime.split(':')[1]}:00Z`
        : undefined,
    actualDuration:
      item.status === 'completed' || item.status === 'invoiced'
        ? item.estimatedDuration - 15
        : undefined,
    branchId:
      item.branchName === 'Dubai Main'
        ? 'branch-001'
        : item.branchName === 'Sharjah Branch'
          ? 'branch-002'
          : 'branch-003',
    branchName: item.branchName,
    assignedTechnicianId: item.assignedTechnicianName
      ? `tech-${item.assignedTechnicianName.toLowerCase().replace(/\s+/g, '-')}`
      : undefined,
    assignedTechnicianName: item.assignedTechnicianName,
    assignedTechnicianPhone: item.assignedTechnicianName ? '+971501234999' : undefined,
    additionalTechnicians: [],
    estimatedCost: item.totalCost ? item.totalCost * 0.85 : undefined,
    laborCharges: item.totalCost ? item.totalCost * 0.6 : undefined,
    partsCost: item.totalCost ? item.totalCost * 0.25 : undefined,
    totalCost: item.totalCost,
    invoiceId: item.status === 'invoiced' ? `inv-${item.id}` : undefined,
    invoiceNumber: item.status === 'invoiced' ? `INV-2026-${item.id.split('-')[1]}` : undefined,
    isRecurring: item.serviceType === 'ac_maintenance',
    recurringFrequency: item.serviceType === 'ac_maintenance' ? 'quarterly' : undefined,
    internalNotes: 'Standard service request. Follow SOP.',
    customerNotes: 'Please call 30 minutes before arrival.',
    attachments: [],
    statusHistory: [
      {
        id: `sh-${item.id}-1`,
        status: 'new',
        changedBy: 'user-001',
        changedByName: 'Admin User',
        changedAt: item.createdAt,
        notes: 'Job created',
      },
      ...(item.status !== 'new'
        ? [
            {
              id: `sh-${item.id}-2`,
              status: 'assigned' as JobStatus,
              changedBy: 'user-001',
              changedByName: 'Admin User',
              changedAt: new Date(new Date(item.createdAt).getTime() + 3600000).toISOString(),
              notes: `Assigned to ${item.assignedTechnicianName ?? 'technician'}`,
            },
          ]
        : []),
      ...(item.status === 'completed' || item.status === 'invoiced'
        ? [
            {
              id: `sh-${item.id}-3`,
              status: 'completed' as JobStatus,
              changedBy: item.assignedTechnicianName
                ? `tech-${item.assignedTechnicianName.toLowerCase().replace(/\s+/g, '-')}`
                : 'user-001',
              changedByName: item.assignedTechnicianName ?? 'Admin User',
              changedAt: new Date(
                new Date(item.scheduledDate).getTime() + item.estimatedDuration * 60000,
              ).toISOString(),
              notes: 'Job completed successfully',
            },
          ]
        : []),
    ],
    serviceReportId: item.hasServiceReport ? `sr-${item.id}` : undefined,
    hasServiceReport: item.hasServiceReport,
    customerRating: item.customerRating,
    hasFeedback: item.hasFeedback,
    createdBy: 'user-001',
    createdByName: 'Admin User',
    createdAt: item.createdAt,
    updatedAt: '2026-02-19T12:00:00Z',
  }
}

